CREATE SCHEMA IF NOT EXISTS workbench;

CREATE TABLE IF NOT EXISTS workbench.api (
  api_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  api_bk TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  endpoint TEXT NOT NULL DEFAULT '',
  http_method TEXT NOT NULL DEFAULT 'GET',
  path TEXT NOT NULL DEFAULT '',
  domain TEXT NOT NULL DEFAULT '',
  api_type TEXT NOT NULL DEFAULT 'REST',
  version TEXT NOT NULL DEFAULT 'v1.0',
  lifecycle TEXT NOT NULL DEFAULT 'Draft',
  owner TEXT NOT NULL DEFAULT '',
  consumers_cnt INTEGER NOT NULL DEFAULT 0,
  status TEXT NOT NULL DEFAULT 'Active',
  environment TEXT NOT NULL DEFAULT 'Production',
  restricted_flag BOOLEAN NOT NULL DEFAULT FALSE,
  test_tool TEXT NOT NULL DEFAULT 'Swagger',
  calls_label TEXT NOT NULL DEFAULT '0',
  latency_label TEXT NOT NULL DEFAULT '--',
  error_rate_label TEXT NOT NULL DEFAULT '--',
  error_level TEXT NOT NULL DEFAULT 'muted',
  trend_label TEXT NOT NULL DEFAULT 'new',
  trend_level TEXT NOT NULL DEFAULT 'muted',
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT api_lifecycle_chk CHECK (lifecycle IN ('Draft', 'Published', 'Deprecated')),
  CONSTRAINT api_environment_chk CHECK (environment IN ('Development', 'QA', 'Production'))
);

CREATE TABLE IF NOT EXISTS workbench.tag_definition (
  tag_name TEXT PRIMARY KEY,
  category TEXT NOT NULL,
  description TEXT NOT NULL,
  owner TEXT NOT NULL,
  rules_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  color TEXT NOT NULL DEFAULT 'hsl(var(--muted))',
  background TEXT NOT NULL DEFAULT 'hsl(var(--muted) / 0.12)'
);

CREATE TABLE IF NOT EXISTS workbench.api_tag (
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  tag_name TEXT NOT NULL REFERENCES workbench.tag_definition (tag_name),
  PRIMARY KEY (api_key, tag_name)
);

CREATE TABLE IF NOT EXISTS workbench.api_sample (
  api_key INTEGER PRIMARY KEY REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  request_json JSONB,
  response_json JSONB
);

CREATE TABLE IF NOT EXISTS workbench.api_explanation (
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  audience TEXT NOT NULL,
  summary TEXT NOT NULL,
  evaluates_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  returns_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  PRIMARY KEY (api_key, audience),
  CONSTRAINT explanation_audience_chk CHECK (audience IN ('Business', 'Developer', 'Partner'))
);

CREATE TABLE IF NOT EXISTS workbench.api_document (
  api_key INTEGER PRIMARY KEY REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  purpose TEXT NOT NULL,
  when_to_use TEXT NOT NULL,
  notes_json JSONB NOT NULL DEFAULT '[]'::jsonb,
  errors_json JSONB NOT NULL DEFAULT '[]'::jsonb
);

CREATE TABLE IF NOT EXISTS workbench.api_schema_field (
  field_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  section TEXT NOT NULL,
  field_name TEXT NOT NULL,
  field_type TEXT NOT NULL,
  required_flag BOOLEAN NOT NULL DEFAULT TRUE,
  description TEXT NOT NULL DEFAULT '',
  example TEXT NOT NULL DEFAULT '',
  sort_order INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT schema_section_chk CHECK (section IN ('path', 'request', 'response'))
);

CREATE INDEX IF NOT EXISTS api_schema_field_api_idx ON workbench.api_schema_field (api_key, section, sort_order);

CREATE TABLE IF NOT EXISTS workbench.api_changelog (
  changelog_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  change_dt DATE NOT NULL,
  version TEXT NOT NULL,
  change_type TEXT NOT NULL,
  title TEXT NOT NULL,
  description TEXT NOT NULL,
  impact TEXT NOT NULL,
  developer_action TEXT NOT NULL,
  owner TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS api_changelog_api_idx ON workbench.api_changelog (api_key, change_dt DESC);

CREATE TABLE IF NOT EXISTS workbench.download (
  download_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key),
  artifact_name TEXT NOT NULL,
  downloaded_by TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS download_created_idx ON workbench.download (created_at DESC);

CREATE TABLE IF NOT EXISTS workbench.app_user (
  user_key TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  team TEXT NOT NULL,
  role_name TEXT NOT NULL,
  access_scope TEXT NOT NULL,
  status TEXT NOT NULL,
  last_active TEXT NOT NULL,
  expires_on TEXT NOT NULL,
  CONSTRAINT user_status_chk CHECK (status IN ('Active', 'Pending', 'Suspended'))
);

CREATE TABLE IF NOT EXISTS workbench.user_api_access (
  user_key TEXT NOT NULL REFERENCES workbench.app_user (user_key) ON DELETE CASCADE,
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  PRIMARY KEY (user_key, api_key)
);

CREATE TABLE IF NOT EXISTS workbench.role_permission (
  role_name TEXT PRIMARY KEY,
  docs TEXT NOT NULL,
  try_it TEXT NOT NULL,
  publish TEXT NOT NULL,
  approve TEXT NOT NULL,
  admin_access TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS workbench.access_request (
  request_key TEXT PRIMARY KEY,
  requester TEXT NOT NULL,
  team TEXT NOT NULL,
  api_name TEXT NOT NULL,
  access_type TEXT NOT NULL,
  risk TEXT NOT NULL,
  reason TEXT NOT NULL,
  requested_at TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Pending',
  CONSTRAINT request_status_chk CHECK (status IN ('Pending', 'Approved', 'Denied')),
  CONSTRAINT request_risk_chk CHECK (risk IN ('Low', 'Medium', 'High'))
);

CREATE TABLE IF NOT EXISTS workbench.audit_event (
  audit_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_label TEXT NOT NULL,
  actor TEXT NOT NULL,
  action TEXT NOT NULL,
  target TEXT NOT NULL,
  result TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS workbench.usage_daily (
  usage_dt DATE NOT NULL,
  api_key INTEGER NOT NULL REFERENCES workbench.api (api_key) ON DELETE CASCADE,
  call_cnt INTEGER NOT NULL DEFAULT 0,
  error_cnt INTEGER NOT NULL DEFAULT 0,
  latency_ms INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (usage_dt, api_key)
);

CREATE TABLE IF NOT EXISTS workbench.trace_object (
  object_bk TEXT PRIMARY KEY,
  kind TEXT NOT NULL,
  title TEXT NOT NULL,
  status TEXT NOT NULL,
  status_color TEXT NOT NULL,
  opened_ago TEXT NOT NULL,
  opened_by TEXT NOT NULL,
  fields_json JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT trace_kind_chk CHECK (kind IN ('Policy', 'Submission', 'Claim'))
);

CREATE TABLE IF NOT EXISTS workbench.trace_relation (
  object_bk TEXT NOT NULL REFERENCES workbench.trace_object (object_bk) ON DELETE CASCADE,
  related_bk TEXT NOT NULL,
  relation TEXT NOT NULL,
  PRIMARY KEY (object_bk, related_bk)
);

CREATE TABLE IF NOT EXISTS workbench.trace_event (
  event_key INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  object_bk TEXT NOT NULL REFERENCES workbench.trace_object (object_bk) ON DELETE CASCADE,
  seq INTEGER NOT NULL,
  event_time TEXT NOT NULL,
  api_name TEXT NOT NULL,
  http_method TEXT NOT NULL,
  path TEXT NOT NULL,
  status_code INTEGER NOT NULL,
  duration_ms INTEGER NOT NULL,
  actor_name TEXT NOT NULL,
  actor_kind TEXT NOT NULL,
  note TEXT NOT NULL DEFAULT '',
  CONSTRAINT trace_actor_kind_chk CHECK (actor_kind IN ('user', 'system')),
  UNIQUE (object_bk, seq)
);
